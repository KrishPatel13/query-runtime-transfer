"""Tails and bias of the per-query error at one query per template (exploratory).

Added on 8 October 2026 after an internal review; not a registered test.

The paper's error is a geometric mean of per-template medians. This script
reports, for the same protocol as src/paper_eval.py (forest model, round
robin, 20 random orders, k = kH: 25 on TPC-H and 100 on TPC-DS, scored on
B's test set), the 90th and 99th percentiles of the per-query Q-error over
the test queries, and the size of the bias: the median signed log error
(log prediction minus log runtime), averaged over the orders, as a factor
exp(|bias|) (1 is unbiased), for no adaptation, the speed factor, the
primary method and the oracle. Per pair the percentiles are averaged in log
over the orders; the macros are geometric means over the 30 moved pairs of
each workload.

Writes into --out (default results/paper/extra):
  tails.json           per workload, pair and method: p90, p99, bias
  tails_numbers.tex    Xtl<W><Stat><Method>, Stat PNinety, PNinetyNine or
                       Bias, Method None, Speed, Primary or Oracle

Usage: python src/paper_tails.py [--runs results/runs] [--out results/paper/extra] [--jobs 16]
"""
from __future__ import annotations

import argparse
import json
import math
from itertools import permutations
from pathlib import Path

import numpy as np
from joblib import Parallel, delayed

import adapt_eval as ae
import paper_eval as pe

HERE = Path(__file__).resolve().parents[1]
WORKLOAD = {"tpch": "Tpch", "tpcds": "Tpcds"}
KH = {"tpch": 25, "tpcds": 100}
METHODS = {pe.NONE: "None", pe.SPEED: "Speed", pe.LOWDIM_TPL: "Primary", pe.ORACLE: "Oracle"}


def job(w: str, a: str, b: str, labels: dict, split) -> dict:
    p = ae.Pair(labels, split, a, b, fit=pe.fit_hybrid)
    orders = ae.arrival_orders(split, pe.ORDERS)
    oracle = pe.fit_hybrid(p.pool, ae.SOURCE_SEED)(p.test)
    y = np.log(p.y_test_ms)
    stats = {m: {"p90": [], "p99": [], "bias": []} for m in METHODS}
    for r, order in enumerate(orders):
        seq = pe.strategy_sequence("round-robin", p, p.positions(order), r, KH[w])
        preds = pe.predictions(p, seq, list(METHODS), pe.fit_hybrid, r, oracle, {})
        for m, pred in preds.items():
            d = pred - y
            q = np.abs(d)
            stats[m]["p90"].append(float(np.quantile(q, 0.9)))
            stats[m]["p99"].append(float(np.quantile(q, 0.99)))
            stats[m]["bias"].append(float(np.median(d)))
    out = {"workload": w, "pair": ae.pair_name(a, b)}
    for m, s in stats.items():
        # The bias's size: its sign flips between a pair and its reverse, which would cancel over pairs.
        out[m] = {"p90": float(np.exp(np.mean(s["p90"]))), "p99": float(np.exp(np.mean(s["p99"]))),
                  "bias": float(np.exp(abs(np.mean(s["bias"]))))}
    return out


def gm(xs: list[float]) -> float:
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=HERE / "results" / "runs")
    ap.add_argument("--out", type=Path, default=HERE / "results" / "paper" / "extra")
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    jobs = []
    for w in WORKLOAD:
        labels, split = pe.load_workload(w, a.runs)
        jobs += [(w, x, y, labels, split) for x, y in permutations(sorted(labels), 2)]
    rows = Parallel(n_jobs=a.jobs, verbose=5)(delayed(job)(*j) for j in jobs)
    (a.out / "tails.json").write_text(json.dumps(rows, indent=1) + "\n", encoding="utf-8")
    m = {}
    for w, W in WORKLOAD.items():
        ws = [r for r in rows if r["workload"] == w]
        for meth, M in METHODS.items():
            for stat, S in (("p90", "PNinety"), ("p99", "PNinetyNine"), ("bias", "Bias")):
                m[f"Xtl{W}{S}{M}"] = f"{gm([r[meth][stat] for r in ws]):.2f}"
    (a.out / "tails_numbers.tex").write_text(
        "% Generated by src/paper_tails.py. Do not edit by hand.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()), encoding="utf-8", newline="\n")
    for k, v in m.items():
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
