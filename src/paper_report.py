def fig_shift(sv: pd.DataFrame, out: Path) -> None:
    """Template slowdowns of every pair, plans with and without parallel workers apart."""
    if sv is None or sv.empty:
        return
    keep = [(w, p) for (w, p) in sv[["workload", "pair"]].drop_duplicates().itertuples(index=False)
            if p in ("M1->M2", "M1->M3", "M1->M5")]
