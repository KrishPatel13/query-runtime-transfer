def fmt(x, d=2):
    return "--" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def arrow(pair: str) -> str:
    a, b = pair.split("->")
    return f"{a}$\\to${b}"


def table_main(jobs: dict, workload: str, out: Path, ks=(10, 25, 100)) -> None:
    """Per pair: the shift, then the error of the main methods at a few budgets."""
    pairs = pairs_of(jobs, workload)
    head = ["Pair", "Change", "Slowdown", "Share"] + [f"Speed {k}" for k in ks] + \
           [f"Primary {k}" for k in ks] + ["Oracle"]
    lines = [GENERATED, "\\begin{tabular}{ll" + "r" * (len(head) - 2) + "}", "\\toprule",
             " & ".join(head) + " \\\\", "\\midrule"]
    for p in pairs:
        j = jobs[(workload, "hybrid", p)]
        sh = j.get("shift", {})
        cells = [arrow(p), CHANGE_NAME.get(j["change"], j["change"] or ""), fmt(sh.get("median")),
                 fmt(sh.get("template_share"))]
        cells += [fmt((cell(j, "random", "speed", k) or {}).get("q")) for k in ks]
        cells += [fmt((cell(j, *PRIMARY, k) or {}).get("q")) for k in ks]
        cells += [fmt((cell(j, "random", "oracle", ks[0]) or {}).get("q"))]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / f"table_main_{workload}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


