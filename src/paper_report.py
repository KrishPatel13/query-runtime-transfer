def tex_name(*parts) -> str:
    words = []
    for p in parts:
        for w in re.split(r"[^A-Za-z0-9]+", str(p)):
            if not w:
                continue
            w = re.sub(r"\d", lambda m: "zero one two three four five six seven eight nine".split()[int(m.group())]
                       .capitalize(), w)
            words.append(w[0].upper() + w[1:])
    return "".join(words)


def macros(jobs: dict, hyp: dict) -> dict:
    m = {}
    for (w, src, pair), j in jobs.items():
        if src != "hybrid":
            continue
        base = ("P", w, pair.replace("->", "to"))
        sh = j.get("shift", {})
        if sh:
            m[tex_name(*base, "slowdown")] = fmt(sh.get("median"))
            m[tex_name(*base, "share")] = fmt(sh.get("template_share"))
            m[tex_name(*base, "r2lot")] = fmt(sh.get("r2_lot"))
        for (strat, meth) in [("random", "speed"), ("random", "ridge"), ("random", "affine+parallel"),
                              PRIMARY, ("random", "oracle"), ("k-center", "1-nn")]:
            for k in (5, 10, 25, 100):
                c = cell(j, strat, meth, k)
                if c:
                    m[tex_name(*base, strat, meth, "k", k)] = fmt(c["q"])
    for h in ("H1", "H2", "H3", "H4", "H5"):
        if h in hyp:
            m[tex_name("Hyp", h, "pass")] = "holds" if hyp[h]["pass"] else "fails"
    return m


def row_macros(srows: list[dict], arows: list[dict], selrows: list[dict], hyp: dict) -> dict:
    """Macros for the tables' numbers: shift rows (PS...), adaptation by change (PA...),
    selection (PL...) and the confirmatory tests (PH...)."""
    m = {}
    for r in srows:
        for f in ("slowdown", "serial", "parallel_x", "share", "noise", "r2_parallel", "r2_size", "r2_both",
                  "r2_template", "r2_lot"):
            m[tex_name("PS", r["workload"], r["pair"].replace("->", "to"), f)] = fmt(r[f])
    for r in arows:
        for key, v in r.items():
            if "|" in key:
                m[tex_name("PA", r["workload"], r["change"], key.replace("|", " "))] = fmt(v)
    for r in selrows:
        for meth in SEL_METHODS + [f"{x}|vs_random" for x in SEL_METHODS] + ["calibration_s"]:
            d = 1 if meth == "calibration_s" else (3 if "vs_random" in meth else 2)
            m[tex_name("PL", r["workload"], "k", r["k"], r["strategy"], meth.replace("|", " "))] = fmt(r[meth], d)
    for h in ("H1", "H2", "H3", "H4", "H5"):
        if h not in hyp:
            continue
        for key, v in hyp[h].items():
            if key in ("rule",):
                continue
            if isinstance(v, bool):
                m[tex_name("PH", h, key)] = "holds" if v else "fails"
            elif isinstance(v, (int, np.integer)):
                m[tex_name("PH", h, key)] = str(int(v))
            elif isinstance(v, float):
                m[tex_name("PH", h, key)] = fmt(v)
    m["PHPairs"] = str(hyp.get("n_pairs", 0))
    # Ranges over the kinds of change (adaptation) and over the pairs (shift), per workload.
    for w in ("tpch", "tpcds"):
        ar = [r for r in arows if r["workload"] == w]
        for key in (ar[0] if ar else {}):
            if "|" in key:
                vals = [r[key] for r in ar if np.isfinite(r[key])]
                if vals:
                    m[tex_name("PAR", w, key.replace("|", " "), "min")] = fmt(min(vals))
                    m[tex_name("PAR", w, key.replace("|", " "), "max")] = fmt(max(vals))
        sr = [r for r in srows if r["workload"] == w]
        for f in ("share", "noise", "r2_parallel", "r2_size", "r2_both", "r2_template", "r2_lot"):
            vals = [r[f] for r in sr if r[f] is not None and np.isfinite(r[f])]
            if vals:
                m[tex_name("PSR", w, f, "min")] = fmt(min(vals))
                m[tex_name("PSR", w, f, "max")] = fmt(max(vals))
    return m


def extra_macros(jobs: dict, runs: Path, srows: list[dict], lrows: list[dict], hyp: dict) -> dict:
    """Numbers the text quotes beyond the tables: noise range, interval counts, per-workload counts."""
    m = {}
    vals = []
    for d in runs.iterdir() if runs.exists() else []:
        f = d / "noise.json"
        if f.exists():
            ptp = json.loads(f.read_text(encoding="utf-8")).get("pass_to_pass") or {}
            if "median_q" in ptp:
                vals.append(ptp["median_q"])
    if vals:
        m["NoiseMedQMin"], m["NoiseMedQMax"] = fmt(min(vals)), fmt(max(vals))
    moved = {w: [jobs[(w, "hybrid", p)] for p in pairs_of(jobs, w)] for w in ("tpch", "tpcds")}
    # H4 over every moved pair, not only the confirmatory ones
    ratios = [j["hard"]["random|speed"]["q"] / j["hard"]["random|oracle"]["q"]
              for w in moved for j in moved[w] if "hard" in j]
    if ratios:
        m["PHHFourMaxAll"] = fmt(max(ratios))
        m["PHHFourAllPairs"] = str(len(ratios))
    # H3 and H5 counted by interval instead of by ratio
    rows = hyp.get("pairs", [])
    h3, h5 = 0, 0
    for (w, src, pair), j in jobs.items():
        if src != "hybrid" or not confirmatory(w, pair):
            continue
        a3 = (cell(j, "random", "affine+parallel", 10) or {}).get("vs_speed") or {}
        if j["change"] in ("processors", "both") and a3.get("gm_hi", 9) < 1:
            h3 += 1
        c5 = (cell(j, "k-center", "1-nn", 100) or {}).get("vs_ridge") or {}
        if c5.get("gm_hi", 9) < 1:
            h5 += 1
    m["PHHThreeOkCI"], m["PHHFiveOkCI"] = str(h3), str(h5)
    for w, js in moved.items():
        W = WORKLOAD_NAME[w].replace("-", "")
        below = sum((cell(j, "random", "affine+parallel", 10) or {}).get("vs_speed", {}).get("gm_hi", 9) < 1 for j in js)
        above = sum((cell(j, "random", "affine+parallel", 10) or {}).get("vs_speed", {}).get("gm_lo", 0) > 1 for j in js)
        m[f"PAff{W}Below"], m[f"PAff{W}Above"], m[f"PAff{W}Pairs"] = str(below), str(above), str(len(js))
        k = 25 if w == "tpch" else 100
        po = [(cell(j, "round-robin", "lowdim+template", k) or {}) for j in js]
        orc = [(cell(j, "random", "oracle", k) or {}).get("q") for j in js]
        rat = [c.get("q") / o for c, o in zip(po, orc) if c.get("q") and o]
        if rat:
            m[f"PPrimOracle{W}Min"], m[f"PPrimOracle{W}Max"] = fmt(min(rat)), fmt(max(rat))
        nn = [(cell(j, "k-center", "1-nn", k) or {}).get("q") for j in js]
        m[f"PNnBelowPrim{W}"] = str(sum(1 for a, b in zip(nn, po) if a and b.get("q") and a < b["q"]))
        for kk in (5, 10, 25, 100):
            m[tex_name("PSpeed", w, "k", kk)] = fmt(geo([(cell(j, "random", "speed", kk) or {}).get("q") for j in js]))
            m[tex_name("PNone", w, "k", kk)] = fmt(geo([(cell(j, "random", "none", kk) or {}).get("q") for j in js]))
        # within-template spread of the log runtime on the first machine
        lab = runs / RUN_DIRS[w]["M1"] / "labels.csv"
        if lab.exists():
            d = pd.read_csv(lab)
            d = d[d["status"] == "ok"]
            sd = d.assign(l=np.log(d["label_ms"])).groupby("template")["l"].std(ddof=1).dropna()
            m[f"PSpread{W}"] = fmt(float(np.exp(np.median(sd))))
            m[f"PSpread{W}Small"] = str(int((sd < 0.1).sum()))
            m[f"PSpread{W}Templates"] = str(int(len(sd)))
        sr = [r for r in srows if r["workload"] == w and r.get("epsilon2") is not None]
        if sr:
            m[tex_name("PSR", w, "epsilon2", "min")] = fmt(min(r["epsilon2"] for r in sr))
            m[tex_name("PSR", w, "epsilon2", "max")] = fmt(max(r["epsilon2"] for r in sr))
    for r in lrows:
        for w in ("tpch", "tpcds"):
            m[tex_name("PLad", w, r["method"].replace("(control)", "control"), r["strategy"])] = fmt(r[w])
    return m


