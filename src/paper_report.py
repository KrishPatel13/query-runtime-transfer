def ladder_rows(jobs: dict) -> list[dict]:
    """Every method at the budget of one query per template (k = 25 on TPC-H, 100 on TPC-DS), as the
    geometric mean over all moved pairs, and the no-move control: the primary method applied to a
    model trained on the target itself, with the same k queries (geometric mean over machines)."""
    rows = []
    for name, strat, m in LADDER:
        row = {"name": name, "strategy": strat, "method": m}
        for w, k in PAPER_SEL:
            js = [jobs[(w, "hybrid", p)] for p in pairs_of(jobs, w)]
            row[w] = geo([(cell(j, strat, m, k) or {}).get("q") for j in js])
        rows.append(row)
    row = {"name": "No move: primary", "strategy": "round-robin",
           "method": "lowdim+template (control)"}
    for w, k in PAPER_SEL:
        cs = [jobs[(w, "hybrid", p)] for p in controls_of(jobs, w)]
        row[w] = geo([(cell(j, "round-robin", "lowdim+template", k) or {}).get("q") for j in cs])
    rows.append(row)
    return rows


