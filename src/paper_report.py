def geo(values: list[float]) -> float:
    v = [x for x in values if x is not None and np.isfinite(x)]
    return float(np.exp(np.mean(np.log(v)))) if v else float("nan")


def adapt_rows(jobs: dict) -> list[dict]:
    """Per workload and kind of change: the geometric mean over its ordered pairs of each method's error."""
    rows = []
    for w in ("tpch", "tpcds"):
        for grp in GROUPS:
            pairs = [p for p in pairs_of(jobs, w) if jobs[(w, "hybrid", p)]["change"] == grp]
            if not pairs:
                continue
            js = [jobs[(w, "hybrid", p)] for p in pairs]
            row = {"workload": w, "change": grp, "pairs": len(pairs)}
            for name, strat, m, k in ADAPT_COLS:
                row[f"{strat}|{m}|{k}"] = geo([(cell(j, strat, m, k) or {}).get("q") for j in js])
            for name, key in HARD_COLS:
                row[f"hard|{key}"] = geo([j.get("hard", {}).get(key, {}).get("q") for j in js])
            rows.append(row)
    return rows


