def selection_rows(jobs: dict, ks=(25, 100)) -> list[dict]:
    """Per workload, k and strategy: geometric mean over all pairs of each method's error, and the
    median over pairs of the ratio to the same method with random selection (the selection effect)."""
    rows = []
    for w in ("tpch", "tpcds"):
        js = [jobs[(w, "hybrid", p)] for p in pairs_of(jobs, w)]
        for k in ks:
            for s in SEL_STRATEGIES:
                row = {"workload": w, "k": k, "strategy": s}
                for m in SEL_METHODS:
                    row[m] = geo([(cell(j, s, m, k) or {}).get("q") for j in js])
                    rr = [(cell(j, s, m, k) or {}).get("vs_random", {}).get("gm") for j in js]
                    rr = [x for x in rr if x is not None]
                    row[f"{m}|vs_random"] = float(np.median(rr)) if rr else float("nan")
                row["calibration_s"] = geo([j.get("calibration_s", {}).get(f"{s}|{k}") for j in js])
                rows.append(row)
    return rows


