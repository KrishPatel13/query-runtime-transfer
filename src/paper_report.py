def r2(y: np.ndarray, X: np.ndarray) -> float:
    """In-sample R^2 of least squares with an intercept."""
    X = np.c_[np.ones(len(y)), X]
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    res = y - X @ beta
    return float(1 - res @ res / ((y - y.mean()) @ (y - y.mean())))


def shift_rows(jobs: dict, sv: pd.DataFrame, runs: Path) -> list[dict]:
    """One row per workload and unordered pair: how the log slowdown r = log(t_B / t_A) splits.

    share: the part of the variance of r between templates; noise: the same
    share between the source machine's own passes. The R^2 columns are of
    least-squares fits of r on: whether the plan has parallel workers; the
    log of the source label (size); both with their interaction; the
    template (one indicator per template); r2_lot: ridge on the 19 plan
    features, each template (TPC-DS family) predicted by a model fitted
    without it.
    """
    rows = []
    for w in ("tpch", "tpcds"):
        for p in pairs_of(jobs, w):
            a, b = p.split("->")
            if MACHINES.index(a) > MACHINES.index(b):
                continue
            j = jobs[(w, "hybrid", p)]
            g = sv[(sv["workload"] == w) & (sv["pair"] == p)]
            lab = pd.read_csv(runs / RUN_DIRS[w][a] / "labels.csv").set_index("query_id")
            size = np.log(lab.loc[g["query_id"], "label_ms"].to_numpy(float))
            r = g["r"].to_numpy(float)
            par = g["parallel"].to_numpy().astype(float)
            tpl = pd.get_dummies(g["template"].astype(str)).to_numpy(float)[:, 1:]
            sh = j["shift"]
            rows.append({"workload": w, "pair": p, "change": j["change"], "slowdown": sh["median"],
                         "serial": sh["by_plan"]["serial"]["median"], "parallel_x": sh["by_plan"]["parallel"]["median"],
                         "share": sh["template_share"], "noise": sh.get("share_noise"),
                         "epsilon2": sh.get("epsilon2"),
                         "r2_parallel": r2(r, par[:, None]), "r2_size": r2(r, size[:, None]),
                         "r2_both": r2(r, np.c_[par, size, par * size]), "r2_template": r2(r, tpl),
                         "r2_lot": sh["r2_lot"]})
    return rows


