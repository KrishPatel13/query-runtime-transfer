Q_TICKS = (1, 1.05, 1.1, 1.2, 1.3, 1.5, 2, 2.5, 3, 4, 5, 7, 10)


def style(ax):
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(labelsize=7)
    ax.grid(axis="y", color="#e6e6e6", lw=0.6)


def log_ticks(ax, lo: float, hi: float, ticks=Q_TICKS, axis: str = "y") -> None:
    """Plain-number ticks on a log axis between lo and hi (no 10^x labels, no minor ticks)."""
    shown = [t for t in ticks if lo * 0.98 <= t <= hi * 1.02]
    if len(shown) < 2:
        shown = [round(lo, 2), round(hi, 2)]
    setter = ax.set_yticks if axis == "y" else ax.set_xticks
    labels = ax.set_yticklabels if axis == "y" else ax.set_xticklabels
    setter(shown)
    labels([f"{t:g}" for t in shown])
    ax.minorticks_off()


def save(fig, out: Path, name: str) -> None:
    fig.savefig(out / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(out / f"{name}.png", dpi=200, bbox_inches="tight")
    plt.close(fig)


