    lines = [GENERATED, "\\begin{tabular}{lp{0.48\\columnwidth}p{0.22\\columnwidth}l}", "\\toprule",
             "& Test & Result & \\\\", "\\midrule"]
    for h in ("H1", "H2", "H3", "H4", "H5"):
        if h in hyp:
            lines.append(f"{h} & {hyp[h]['rule']} & {text[h](hyp[h])} & {'holds' if hyp[h]['pass'] else 'fails'} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "table_hypotheses.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


