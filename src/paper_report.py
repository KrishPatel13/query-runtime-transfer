# ------------------------------------------------------------------ loading

def load(run: Path):
    """summary.json (or summary.json.gz, as committed), and the shift vectors."""
    if (run / "summary.json").exists():
        s = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    else:
        import gzip
        s = json.loads(gzip.decompress((run / "summary.json.gz").read_bytes()).decode("utf-8"))
    jobs = {(j["workload"], j["source"], j["pair"]): j for j in s["jobs"]}
    sv = pd.read_csv(run / "shift_vectors.csv") if (run / "shift_vectors.csv").exists() else None
    return s, jobs, sv


def pairs_of(jobs: dict, workload: str, source: str = "hybrid") -> list[str]:
    def key(p):
        a, b = p.split("->")
        return (MACHINES.index(a), MACHINES.index(b))
    return sorted({p for (w, s, p) in jobs if w == workload and s == source
                   and p.split("->")[0] != p.split("->")[1]}, key=key)


def controls_of(jobs: dict, workload: str) -> list[str]:
    """The no-move controls of a workload (a machine as its own source), in machine order."""
    return sorted({p for (w, s, p) in jobs if w == workload and s == "hybrid"
                   and p.split("->")[0] == p.split("->")[1]}, key=lambda p: MACHINES.index(p.split("->")[0]))


def confirmatory(workload: str, pair: str) -> bool:
    """The pairs of paper/PLAN.md's confirmatory tests: M1 to M4 in TPC-DS, and TPC-H pairs with M4.
    M5 was added after the tests were fixed, so its pairs are exploratory."""
    machines = pair.split("->")
    if "M5" in machines or "M6" in machines or machines[0] == machines[1]:
        return False
    return workload == "tpcds" or "M4" in machines


def cell(job: dict, strategy: str, method: str, k: int) -> dict | None:
    return job["c2"].get(f"{strategy}|{method}|{k}")


# --------------------------------------------------------------- hypotheses

def hypotheses(jobs: dict) -> dict:
    """H1 to H5 of paper/PLAN.md, evaluated on the confirmatory pairs only."""
    rows = []
    for (w, src, pair), j in sorted(jobs.items()):
        if src != "hybrid" or not confirmatory(w, pair):
            continue
        sh = j.get("shift", {})
        prim = cell(j, *PRIMARY, 100) or {}
        a3 = cell(j, "random", "affine+parallel", 10) or {}
        h5 = cell(j, "k-center", "1-nn", 100) or {}
        hard = j.get("hard", {})
        hs, ho = hard.get("random|speed", {}).get("q"), hard.get("random|oracle", {}).get("q")
        rows.append({
            "workload": w, "pair": pair, "change": j["change"],
            "share": sh.get("template_share"),
            "h2_vs_speed": prim.get("vs_speed"), "h2_vs_ridge": prim.get("vs_ridge"),
            "h3_ratio": (a3.get("vs_speed") or {}).get("gm"),
            "h4_ratio": hs / ho if hs and ho else None,
            "h5_ratio": (h5.get("vs_ridge") or {}).get("gm"),
        })
    n = len(rows)
    proc = [r for r in rows if r["change"] in ("processors", "both")]
    out = {"pairs": rows, "n_pairs": n}
    if not n:
        return out
    h1 = [r for r in rows if r["share"] is not None]
    out["H1"] = {"rule": "template share > 0.5 in every pair", "pass": all(r["share"] > 0.5 for r in h1),
                 "min": min(r["share"] for r in h1), "n": len(h1)}
    sp = [r for r in rows if r["h2_vs_speed"]]
    rd = [r for r in rows if r["h2_vs_ridge"]]
    sp_ok = sum(r["h2_vs_speed"]["gm_hi"] < 1 for r in sp)
    rd_ok = sum(r["h2_vs_ridge"]["gm_hi"] < 1 for r in rd)
    out["H2"] = {"rule": "k=100: primary beats speed (CI < 1) in every pair and ridge (CI < 1) in >= 2/3",
                 "vs_speed_ok": sp_ok, "vs_ridge_ok": rd_ok, "n": len(sp),
                 "pass": len(sp) > 0 and sp_ok == len(sp) and rd_ok >= math.ceil(2 * len(rd) / 3)}
    h3 = [r for r in proc if r["h3_ratio"] is not None]
    h3_ok = sum(r["h3_ratio"] < 1 for r in h3)
    out["H3"] = {"rule": "k=10: affine+parallel below speed in >= 3/4 of processor pairs", "ok": h3_ok,
                 "n": len(h3), "pass": len(h3) > 0 and h3_ok >= math.ceil(3 * len(h3) / 4)}
    h4 = [r for r in rows if r["h4_ratio"] is not None]
    out["H4"] = {"rule": "hard test: speed / oracle <= 1.15 in every pair",
                 "max": max((r["h4_ratio"] for r in h4), default=None), "n": len(h4),
                 "pass": len(h4) > 0 and all(r["h4_ratio"] <= 1.15 for r in h4)}
    h5 = [r for r in rows if r["h5_ratio"] is not None]
    h5_ok = sum(r["h5_ratio"] < 1 for r in h5)
    out["H5"] = {"rule": "k=100: k-center + 1-nn below random + ridge in >= 2/3", "ok": h5_ok, "n": len(h5),
                 "pass": len(h5) > 0 and h5_ok >= math.ceil(2 * len(h5) / 3)}
    return out


