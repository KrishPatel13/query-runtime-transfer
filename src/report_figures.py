def table_c1(course: dict) -> dict:
    """C1 on one table row per model: seen and unseen median Q-error and the unseen ratio to the cost
    line on each machine; a ratio whose 95% interval lies below 1 is bold."""
    c1 = course["c1"]
    ms = list(c1)
    lines = [GENERATED, "\\begin{tabular}{@{}l" + "c" * (3 * len(ms)) + "@{}}", "\\toprule",
             "& \\multicolumn{3}{c}{Seen: median $Q$} & \\multicolumn{3}{c}{Unseen: median $Q$} "
             "& \\multicolumn{3}{c}{Unseen: ratio} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(l){8-10}",
             "Model & " + " & ".join(ms * 3) + " \\\\", "\\midrule"]
    sd = []
    for name, seen, unseen in C1_MODELS:
        row = [fmt(c1[m]["seen"][seen]["median_q"]) for m in ms]
        sd += [c1[m]["seen"][seen]["median_q_std"] for m in ms]
        row += [fmt(c1[m]["unseen"][unseen]["median_q"]) for m in ms]
        for m in ms:
            r = c1[m]["unseen_paired_vs_cost"].get(unseen)
            if r is None:
                row.append("--")
            else:
                v = fmt(r["gm"])
                row.append(f"\\textbf{{{v}}}" if r["gm_hi"] < 1 else v)
        lines.append(f"{name} & " + " & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "table_c1.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"RCOneSdMax": fmt(max(sd))}


