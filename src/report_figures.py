def env_stats(d: str) -> tuple[float, float, float]:
    """Median pass time in minutes, and the median and P90 Q-error between two passes."""
    walls = []
    for i in (1, 2, 3):
        r = json.loads((RUNS / d / f"pass{i}" / "run.json").read_text(encoding="utf-8"))
        walls.append(sum(c["wall_s"] for c in r.get("clock_rate", [])))
    n = json.loads((RUNS / d / "noise.json").read_text(encoding="utf-8"))["pass_to_pass"]
    return float(np.median(walls)) / 60.0, n["median_q"], n["p90_q"]


def table_envs() -> dict:
    lines = [GENERATED, "\\begin{tabular}{@{}llrcrc@{}}", "\\toprule",
             "& & \\multicolumn{2}{c}{TPC-H} & \\multicolumn{2}{c}{TPC-DS} \\\\",
             "\\cmidrule(lr){3-4}\\cmidrule(l){5-6}",
             "& Setup & Pass & Noise & Pass & Noise \\\\", "\\midrule"]
    macros, noise = {}, []
    for m in MACHINES:
        cells = []
        for w, d in (("tpch", m), ("tpcds", f"{m}_tpcds")):
            minutes, med, p90 = env_stats(d)
            noise.append(med)
            cells += [f"{minutes:.0f}", f"{med:.2f} / {p90:.2f}"]
        lines.append(f"{m} & {ENV_DESC[m]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "table_envs.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    macros["RNoiseMin"], macros["RNoiseMax"] = f"{min(noise):.2f}", f"{max(noise):.2f}"
    return macros


