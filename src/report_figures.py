def arrow(name: str) -> str:
    return name.replace("->", r" $\rightarrow$ ")


def q_ticks(lo: float, hi: float, gap: float = 0.08,
            ticks=(1, 1.05, 1.1, 1.2, 1.3, 1.5, 2, 3, 5, 10, 20, 50, 100, 300)) -> list:
    span = np.log(hi / lo)
    out = []
    for t in ticks:
        if lo <= t <= hi and (not out or np.log(t / out[-1]) >= gap * span):
            out.append(t)
    return out


def swarm(y: np.ndarray, width: float = 0.32, step: float = 0.075, min_dy: float = 0.035) -> np.ndarray:
    """Deterministic beeswarm offsets: in order of y, each point takes the offset nearest 0 that keeps
    it at least min_dy (log units) from the points already placed at that offset."""
    placed, xs = [], np.zeros(len(y))
    cands = [0.0] + [s * step * i for i in range(1, 20) for s in (-1, 1)]
    for i in np.argsort(y):
        for c in cands:
            if abs(c) <= width and all(abs(c - px) >= step * 0.99 or abs(y[i] - py) >= min_dy for px, py in placed):
                xs[i] = c
                placed.append((c, y[i]))
                break
    return xs


def load():
    course = json.loads((COURSE / "summary.json").read_text(encoding="utf-8"))
    paper = json.loads(gzip.decompress((PAPER / "summary.json.gz").read_bytes()).decode("utf-8"))
    jobs = {(j["workload"], j["pair"]): j for j in paper["jobs"] if j["source"] == "hybrid"}
    return course, jobs


def cell(job: dict, strategy: str, method: str, k: int) -> dict | None:
    return job["c2"].get(f"{strategy}|{method}|{k}")


def moved(jobs: dict, w: str) -> list[dict]:
    return [j for (ww, p), j in sorted(jobs.items()) if ww == w and j["a"] != j["b"]]


