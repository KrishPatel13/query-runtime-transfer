def fig_orders(course: dict) -> dict:
    """Per arrival order, the ridge correction's error over the speed factor's; returns the macros."""
    runs = pd.read_csv(COURSE / "c2_runs.csv")
    ks = sorted(runs["k"].unique())
    fig, axes = plt.subplots(1, 3, figsize=(te.FIG_W, 1.65), sharey=True)
    rng = np.random.default_rng(0)
    macros = {}
    for i, (ax, p) in enumerate(zip(axes, COURSE_PAIRS)):
        te.style_axes(ax, logy=True)
        ax.grid(False, axis="x")
        g = runs[runs["pair"] == p]
        piv = g.pivot_table(index=["order", "k"], columns="method", values="mean_log_template_q")
        ratio = np.exp(piv["Ridge correction"] - piv["Speed factor"]).unstack("k")
        for xi, k in enumerate(ks):
            v = ratio[k].to_numpy()
            parts = ax.violinplot([v], positions=[xi], widths=0.7, showextrema=False)
            for b in parts["bodies"]:
                b.set_facecolor(COLORS[RIDGE])
                b.set_alpha(0.2)
                b.set_linewidth(0)
            ax.scatter(xi - 0.12 + rng.uniform(-0.08, 0.08, len(v)), v, s=4, color=COLORS[RIDGE], lw=0, zorder=3)
            r = course["c2"][p]["ridge_vs_speed"][str(k)]
            ax.errorbar(xi + 0.22, r["gm"], yerr=[[r["gm"] - r["gm_lo"]], [r["gm_hi"] - r["gm"]]], fmt="D",
                        color=te.INK, ms=3.5, lw=0.9, capsize=1.8, zorder=4)
            below = int((v < 1).sum())
            ax.text(xi, 1.43, str(below), ha="center", va="bottom", fontsize=te.FS, color=te.INK2)
            macros[tex_name("RBelow", p, "K", k)] = str(below)
        ax.axhline(1.0, color=te.INK2, lw=0.9, zorder=2)
        ax.set_xticks(range(len(ks)))
        ax.set_xticklabels([str(k) for k in ks], fontsize=te.FS)
        ax.set_xlabel("measured target queries $k$", color=te.INK, fontsize=te.FS_LABEL)
        desc = " (descriptive)" if course["c2"][p]["descriptive"] else ""
        ax.set_title(f"({chr(97 + i)}) {arrow(p)}{desc}", color=te.INK, fontsize=te.FS_LABEL, loc="left", pad=10)
        ax.set_ylim(0.72, 1.55)
        te.qerror_axis(ax, ticks=(0.8, 1, 1.2))
    axes[0].set_ylabel("ridge correction's error\nover the speed factor's", color=te.INK, fontsize=te.FS_LABEL)
    handles = [Line2D([], [], marker="o", ls="none", color=COLORS[RIDGE], ms=3, label="one arrival order"),
               Line2D([], [], marker="D", color=te.INK, ms=3.5, lw=0.9,
                      label="mean over orders, 95% interval over templates")]
    fig.legend(handles=handles, loc="upper center", ncol=2, frameon=False, fontsize=te.FS,
               bbox_to_anchor=(0.5, 1.13), columnspacing=1.5)
    fig.tight_layout(w_pad=0.6)
    te.save(fig, OUT / "fig_orders")
    return macros


def fig_unseen(course: dict) -> None:
    per = pd.read_csv(COURSE / "c2_per_template.csv")
    hard = pd.read_csv(COURSE / "c2_hard_per_template.csv")
    c4 = pd.read_csv(COURSE / "c4_predictions.csv")
    fig, axes = plt.subplots(1, 3, figsize=(te.FIG_W, 1.6))
    styles ={"M1->M2": (te.INK2, te.INK2), "M1->M3": ("white", te.INK2)}

    def scatter_pairs(ax, frame, k=None):
        vals = []
        for p, (fc, ec) in styles.items():
            g = frame[frame["pair"] == p]
            if k is not None:
                g = g[g["k"] == k]
            piv = g.pivot_table(index="template", columns="method", values="q")
            ax.scatter(piv["Speed factor"], piv["Ridge correction"], s=10, facecolor=fc, edgecolor=ec,
                       linewidths=0.7, zorder=3)
            vals += list(piv["Speed factor"]) + list(piv["Ridge correction"])
        return vals

    panels = [
        (axes[0], scatter_pairs(axes[0], per, 25), "(a) Seen templates", "speed factor", "ridge correction"),
        (axes[1], scatter_pairs(axes[1], hard), "(b) Held-out template", "speed factor", "ridge correction"),
    ]
    c4 = c4.assign(q=np.maximum(c4["y"] / c4["yhat"], c4["yhat"] / c4["y"]))
    fam = c4.groupby(["template", "model"])["q"].median().unstack("model")
    size = c4.groupby("template")["source_template"].nunique()
    multi = size.reindex(fam.index) > 1
    ax = axes[2]
    ax.scatter(fam.loc[~multi, "Cost-only"], fam.loc[~multi, "Cost + RF residual"], s=6, facecolor="white", alpha=0.7,
               edgecolor=te.INK2, linewidths=0.7, zorder=3)
    ax.scatter(fam.loc[multi, "Cost-only"], fam.loc[multi, "Cost + RF residual"], s=6, facecolor=te.INK2, alpha=0.7,
               edgecolor=te.INK2, linewidths=0.7, zorder=3)
    panels.append((ax, list(fam["Cost-only"]) + list(fam["Cost + RF residual"]), "(c) Held-out TPC-DS family",
                   "cost line", "correction model"))
    for ax, vals, title, xl, yl in panels:
        te.style_axes(ax, logx=True, logy=True)
        hi = max(vals) * 1.15
        ax.plot([1, hi], [1, hi], color=te.MUTED, lw=0.9, zorder=2)
        ax.set_xlim(1, hi)
        ax.set_ylim(1, hi)
        ticks = q_ticks(1, hi, gap=0.2)
        te.qerror_axis(ax, ticks=ticks)
        te.qerror_axis(ax, axis="x", ticks=ticks)
        ax.set_aspect("equal")
        ax.set_title(title, color=te.INK, fontsize=te.FS_LABEL, loc="left")
        ax.set_xlabel(xl, color=te.INK, fontsize=te.FS_LABEL)
        ax.set_ylabel(yl, color=te.INK, fontsize=te.FS_LABEL)
    fig.tight_layout(w_pad=0.8)
    te.save(fig, OUT / "fig_unseen")


