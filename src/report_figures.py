def count(cells: list[dict], key: str, below: bool) -> int:
    """Pairs whose 95% interval of the ratio `key` lies wholly below (or above) 1."""
    out = 0
    for c in cells:
        r = (c or {}).get(key)
        if r and ((r["gm_hi"] < 1) if below else (r["gm_lo"] > 1)):
            out += 1
    return out


def numbers(jobs: dict) -> dict:
    m = {}
    for p in ("M1->M2", "M1->M3", "M3->M1"):
        c = cell(jobs[("tpch", p)], "round-robin", TC, 25)
        r = c["vs_ridge"]
        m[tex_name("RTcVsRidge", p)] = fmt(r["gm"])
        m[tex_name("RTcVsRidge", p, "Lo")] = fmt(r["gm_lo"])
        m[tex_name("RTcVsRidge", p, "Hi")] = fmt(r["gm_hi"])
        m[tex_name("RTcVsRidge", p, "Wins")] = str(r["wins"])
        m[tex_name("RTcGap", p)] = fmt(c["gap"]["g"])
        m[tex_name("RTc", p)] = fmt(c["q"])
        for strat, meth in (("random", SPEED), ("random", RIDGE)):
            m[tex_name("R", meth, p)] = fmt(cell(jobs[("tpch", p)], strat, meth, 25)["q"])
        # The smallest k at which the ridge correction (random) closes 90% of the gap.
        ks = sorted({int(key.split("|")[2]) for key in jobs[("tpch", p)]["c2"]})
        first = next((k for k in ks if cell(jobs[("tpch", p)], "random", RIDGE, k)["gap"]["g"] >= 0.9), None)
        m[tex_name("RRidgeNinety", p)] = str(first) if first else "--"
    for w, (_, kw) in WORKLOADS.items():
        js = moved(jobs, w)
        m[tex_name("RPairs", w)] = str(len(js))
        for k in (5, 10, 25, 50, 100):
            cs = [cell(j, "random", RIDGE, k) for j in js]
            m[tex_name("RRidgeBelow", w, "K", k)] = str(count(cs, "vs_speed", True))
            m[tex_name("RRidgeAbove", w, "K", k)] = str(count(cs, "vs_speed", False))
            m[tex_name("RRidge", w, "K", k)] = fmt(geo([c["q"] for c in cs]))
            m[tex_name("RSpeed", w, "K", k)] = fmt(geo([cell(j, "random", SPEED, k)["q"] for j in js]))
        tc = [cell(j, "round-robin", TC, kw) for j in js]
        m[tex_name("RTcBelowSpeed", w)] = str(count(tc, "vs_speed", True))
        m[tex_name("RTcBelowRidge", w)] = str(count(tc, "vs_ridge", True))
        m[tex_name("RTcGapMin", w)] = fmt(min(c["gap"]["g"] for c in tc))
        m[tex_name("RTcGapMax", w)] = fmt(max(c["gap"]["g"] for c in tc))
        # Held-out templates (TPC-DS: families), k = 25, random selection.
        for meth in ("none", "speed", "ridge", "oracle", "lowdim+template"):
            m[tex_name("RHard", w, meth)] = fmt(geo([j["hard"][f"random|{meth}"]["q"] for j in js]))
