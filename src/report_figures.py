def fig_overview(jobs: dict) -> None:
    sv = pd.read_csv(PAPER / "shift_vectors.csv")
    fig = plt.figure(figsize=(te.FIG_W, 1.75))
    gs = fig.add_gridspec(1, 3, width_ratios=[0.78, 1, 1], wspace=0.34)
    ax0 = fig.add_subplot(gs[0])
    te.style_axes(ax0, logy=True)
    ax0.grid(False, axis="x")
    for i, p in enumerate(("M1->M2", "M1->M3")):
        g = sv[(sv["workload"] == "tpch") & (sv["pair"] == p)]
        tm = g.groupby("template").agg(r=("r", "mean"), par=("parallel", "mean"))
        y = tm["r"].to_numpy()
        x = i + swarm(y)
        kind = np.where(tm["par"] >= 0.999, "parallel", np.where(tm["par"] <= 0.001, "serial", "mixed"))
        for k, (fc, ec) in {"parallel": (te.INK2, te.INK2), "mixed": (te.MUTED, te.MUTED),
                            "serial": ("white", te.INK2)}.items():
            m = kind == k
            ax0.scatter(x[m], np.exp(y[m]), s=11, facecolor=fc, edgecolor=ec, linewidths=0.7, zorder=3)
        ax0.hlines(float(np.exp(g["r"].mean())), i - 0.38, i + 0.38, color=COLORS[SPEED], lw=1.3, zorder=2)
    ax0.set_xlim(-0.55, 1.55)
    ax0.set_xticks([0, 1])
    ax0.set_xticklabels(["M2", "M3"], fontsize=te.FS)
    ax0.set_ylim(0.9, 3.8)
    te.qerror_axis(ax0, ticks=(1, 1.5, 2, 3))
    ax0.set_xlabel("TPC-H, from M1 to", color=te.INK, fontsize=te.FS_LABEL)
    ax0.set_ylabel("slowdown of a template\n(target / M1 runtime)", color=te.INK, fontsize=te.FS_LABEL)
    ax0.set_title("(a) Shift", color=te.INK, fontsize=te.FS_LABEL, loc="left")

    axes = [fig.add_subplot(gs[1]), fig.add_subplot(gs[2])]
    for i, (ax, w) in enumerate(zip(axes, ("tpch", "tpcds"))):
        j = jobs[(w, "M1->M3")]
