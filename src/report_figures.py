def table_methods(jobs: dict) -> None:
    lines = [GENERATED, "\\begin{tabular}{@{}llrr@{}}", "\\toprule",
             "Method & Selection & TPC-H, $k=25$ & TPC-DS, $k=100$ \\\\", "\\midrule"]
    for name, strat, m in METHODS:
        vals = [fmt(geo([(cell(j, strat, m, k) or {}).get("q") for j in moved(jobs, w)]))
                for w, (_, k) in WORKLOADS.items()]
        sel = "" if m in ("none", "oracle") else SEL[strat]
        lines.append(f"{name} & {sel} & {vals[0]} & {vals[1]} \\\\")
    ctrl = []
    for w, (_, k) in WORKLOADS.items():
        cs = [j for (ww, p), j in jobs.items() if ww == w and j["a"] == j["b"]]
        ctrl.append(fmt(geo([(cell(j, "round-robin", TC, k) or {}).get("q") for j in cs])))
    lines += ["\\midrule", f"Template correction, no move & round robin & {ctrl[0]} & {ctrl[1]} \\\\",
              "\\bottomrule", "\\end{tabular}"]
    (OUT / "table_methods.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


