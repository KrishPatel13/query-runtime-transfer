"""The environments table of the full paper (paper/icde), from the saved labels.

Reads results/runs/<environment>/noise.json (written by src/make_labels.py)
for every environment and workload of the study and writes into --out:

  table_env.tex    one row per environment: machine, processors PostgreSQL
                   may use, buffer pool, and the median pass-to-pass Q-error
                   per workload; a cell stays empty where the environment
                   did not run the workload or its labels do not exist yet
  env_numbers.tex  EnvNoiseMedQMin and EnvNoiseMedQMax, the smallest and
                   largest of those medians, and EnvCells, how many there are;
                   EnvPassTpchMin and EnvPassTpchMax, the shortest and longest
                   median time of a TPC-H SF1 pass over the environments, in
                   minutes (the time of its runs, as src/report_figures.py
                   counts it)

Usage: python src/paper_env_table.py [--runs-dir results/runs] [--out results/paper/environments]
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]

# Environment: machine, processors PostgreSQL may use, buffer pool (paper/PLAN.md and STUDY.md).
ENVS = [("M1", "laptop", "all 22", "2\\,GB"), ("M2", "laptop", "1", "2\\,GB"),
        ("M3", "server", "all 64", "2\\,GB"), ("M4", "server", "1", "2\\,GB"),
        ("M5", "laptop", "all 22", "128\\,MB"), ("M6", "server", "2", "2\\,GB")]
# Workload: column heading, suffix of the run directory (M1, M1_tpcds, M3_sf10, M1_job).
WORKLOADS = [("TPC-H", ""), ("TPC-DS", "_tpcds"), ("SF10", "_sf10"), ("JOB", "_job")]


def median_q(runs: Path, name: str) -> float | None:
    f = runs / name / "noise.json"
    if not f.exists():
        return None
    p2p = json.loads(f.read_text(encoding="utf-8")).get("pass_to_pass")
    return p2p["median_q"] if p2p else None


def pass_minutes(runs: Path, name: str) -> float | None:
    """Median over the three passes of the summed wall time of their runs, in minutes."""
    walls = []
    for i in (1, 2, 3):
        f = runs / name / f"pass{i}" / "run.json"
        if not f.exists():
            return None
        walls.append(sum(c["wall_s"] for c in json.loads(f.read_text(encoding="utf-8")).get("clock_rate", [])))
    return statistics.median(walls) / 60.0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs-dir", type=Path, default=HERE / "results" / "runs")
    ap.add_argument("--out", type=Path, default=HERE / "results" / "paper" / "environments")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    head = "% Generated by src/paper_env_table.py. Do not edit by hand.\n"
    lines = [head, "\\begin{tabular}{@{}llllrrrr@{}}\n\\toprule\n",
             "& & & & \\multicolumn{4}{c}{noise, median Q} \\\\\n\\cmidrule(l){5-8}\n",
             "Env. & machine & CPUs & buffers & " + " & ".join(w for w, _ in WORKLOADS) + " \\\\\n\\midrule\n"]
    found = []
    for env, machine, procs, buffers in ENVS:
        cells = []
        for _, suffix in WORKLOADS:
            q = median_q(a.runs_dir, env + suffix)
            cells.append("" if q is None else f"{q:.2f}")
            if q is not None:
                found.append(q)
        lines.append(f"{env} & {machine} & {procs} & {buffers} & " + " & ".join(cells) + " \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    (a.out / "table_env.tex").write_text("".join(lines), encoding="utf-8", newline="\n")
    minutes = [m for m in (pass_minutes(a.runs_dir, env) for env, *_ in ENVS) if m is not None]
    if not found or not minutes:
        raise SystemExit(f"no noise.json or no TPC-H pass under {a.runs_dir}")
    (a.out / "env_numbers.tex").write_text(
        head + f"\\newcommand{{\\EnvNoiseMedQMin}}{{{min(found):.2f}}}\n"
        f"\\newcommand{{\\EnvNoiseMedQMax}}{{{max(found):.2f}}}\n"
        f"\\newcommand{{\\EnvCells}}{{{len(found)}}}\n"
        f"\\newcommand{{\\EnvPassTpchMin}}{{{min(minutes):.0f}}}\n"
        f"\\newcommand{{\\EnvPassTpchMax}}{{{max(minutes):.0f}}}\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out / 'table_env.tex'} ({len(found)} cells) and {a.out / 'env_numbers.tex'}")


if __name__ == "__main__":
    main()
