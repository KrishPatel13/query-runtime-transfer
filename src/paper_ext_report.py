"""Confirmatory tests, macros and tables of the second round (paper/PLAN.md, "Extension for the full paper").

Reads the summary of src/paper_eval.py run on the second round's workloads
(--eval, such as results/paper/ext: summary.json or summary.json.gz) and of
src/paper_nn.py run on them (--nn, such as results/paper/nn_ext: summary.json
and pairs.json.gz), and writes into --out (default: the --eval directory):

  hypotheses_ext.json       H1 to H5, H6, H6a and H6b per experiment, with
                            every pair's statistics
  ext_numbers.tex           a LaTeX macro (prefix X) for every test result and
                            the numbers the paper quotes per experiment
  table_hypotheses_ext.tex  the tests: counts and result per experiment
  table_ext.tex             errors by method at k = 10 and kH per experiment

The experiments are E1 (tpch10, TPC-H at scale factor 10) and E2 (job, the
Join Order Benchmark). Every ordered pair of an experiment's measured
environments is confirmatory (the no-move controls are not pairs). The
rules are the first round's (src/paper_report.py, hypotheses), with the
budget kH (paper_eval.budget: 100 on E1, 33 on E2, one query per template)
in place of k = 100 in H2 and H5, and the tests of H6 as amended on
8 October:
  H1   the template share exceeds 0.5 in every pair
  H2   at kH, the primary method (lowdim+template, round robin) over the
       speed factor (random): interval below 1 in every pair; over the ridge
       correction (random): interval below 1 in at least two thirds
  H3   at k = 10, affine+parallel (random) over the speed factor (random):
       ratio below 1 in at least three quarters of the processor pairs
       (processor_pair)
  H4   in the hard test (k = 25, random), the speed factor's error over the
       oracle's is at most 1.15 in every pair
  H5   at kH, k-center with 1-nn over random with the ridge correction:
       ratio below 1 in at least two thirds
  H6   at kH, the template correction (round robin, on the course study's
       source model) over the network with full fine-tuning on the same
       queries: interval below 1 in at least two thirds of the new pairs.
       The registration says "of the new pairs", not "of each experiment"
       as it does for H1 to H5 and H6a, and the first round counted such a
       rule over all its pairs, so H6 is one count over every pair of E1
       and E2, each at its own kH (pooled_h6, "all" in hypotheses_ext.json,
       macros XAllHSix...). The counts per experiment are descriptive and
       carry no result.
  H6a  at k = 10, that ratio's point estimate below 1 in more than half of
       the pairs of each experiment, and its geometric mean over them below 1
  H6b  at kH, the upper end of that ratio's interval below 1.15 in every pair
As in the first round (paper_report.extra_macros), H3 and H5 are also counted
by interval, and so are H6a and the affine+parallel line against the speed
factor over all pairs; fine-tuning of the head only is reported beside full
fine-tuning. Without --nn, H6 to H6b are left out.

Macro names: X<Workload><what>, with Workload TpchTen or Job as in
src/paper_nn_report.py and numbers spelled digit by digit as in
src/paper_report.py (k = 33 is KThreeThree, kH also KH); a test's counts are
X<Workload>H<n><key> (H6a is HSixa), its result X<Workload>H<n>Pass; H6 over
all new pairs is XAllHSix<key>.

Before writing anything, main checks what it was given and says so: the
environments of every experiment against the registered ones
(paper_eval.WORKLOADS), every pair's pool and test sizes against the split
and the queries it left out, and, with --nn, that paper_nn's reference check
found its course-study cells equal to paper_eval's (README: max_abs_log_diff
0). A missing environment or a dropped query is printed as a warning and
recorded in hypotheses_ext.json; a failed or missing reference check stops
the script.

Usage: python src/paper_ext_report.py --eval results/paper/ext --nn results/paper/nn_ext
"""
