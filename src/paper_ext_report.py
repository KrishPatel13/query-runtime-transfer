def count_text(test: str, h: dict) -> str:
    if test == "H2":
        return f"{h['vs_speed_ok']}/{h['n']}, {h['vs_ridge_ok']}/{h['n_ridge']}"
    if test == "H6a":
        return f"{h['point']}/{h['n']}, {fmt_level(h['gm'], 1.0, 3)}"
    return f"{h['ok']}/{h['n']}"


def table_hypotheses(hyp: dict, out: Path, pooled: dict | None = None) -> None:
    """One row per test and experiment; H6, registered over all new pairs, spans the experiments' columns
    with the pooled count and result and each experiment's count beside it."""
    ws = [w for w in EXPERIMENTS if w in hyp]
    lines = [GENERATED, "\\begin{tabular}{@{}ll" + "rl" * len(ws) + "@{}}", "\\toprule",
             "& & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{EXPERIMENTS[w]}: {DISPLAY[w]}}}" for w in ws) + " \\\\",
             "".join(f"\\cmidrule({'lr' if i < len(ws) - 1 else 'l'}){{{3 + 2 * i}-{4 + 2 * i}}}"
                     for i in range(len(ws))),
             "& Test & " + " & ".join("Count & Result" for _ in ws) + " \\\\", "\\midrule"]
    for test in TESTS:
        if not any(test in hyp[w] for w in ws):
            continue
        cells = [test, RULE_TEXT[test]]
        if test == "H6":
            if pooled and "H6" in pooled:
                p = pooled["H6"]
                by = ", ".join(f"{EXPERIMENTS[w]} {hyp[w]['H6']['ok']}/{hyp[w]['H6']['n']}" for w in ws if "H6" in hyp[w])
                cells.append(f"\\multicolumn{{{2 * len(ws)}}}{{c}}{{all new pairs {p['ok']}/{p['n']} ({by}): "
                             f"{'holds' if p['pass'] else 'fails'}}}")
            else:
                cells.append(f"\\multicolumn{{{2 * len(ws)}}}{{c}}{{--}}")
            lines.append(" & ".join(cells) + " \\\\")
            continue
        for w in ws:
            h = hyp[w].get(test)
            cells += [count_text(test, h), "holds" if h["pass"] else "fails"] if h else ["--", "--"]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "table_hypotheses_ext.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def table_errors(jobs: dict, hyp: dict, nn_summary: dict | None, out: Path) -> None:
    """Geometric mean over pairs of every method's error at k = 10 and kH, the no-move control apart."""
    ws = [w for w in EXPERIMENTS if w in hyp]
    errs = {(w, k): errors(jobs, nn_summary, w, k) for w in ws for k in (SMALL_K, hyp[w]["kh"])}
    rows = [(word, label) for word, label, _, _ in ERRORS[:-1]]
    if nn_summary is not None:
        rows += [(word, label) for word, label, _ in NN_ERRORS]
    rows += [(ERRORS[-1][0], ERRORS[-1][1]), None, ("Control", "No move: primary")]
    lines = [GENERATED, "\\begin{tabular}{@{}l" + "rr" * len(ws) + "@{}}", "\\toprule",
             "& " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{EXPERIMENTS[w]}: {SHORT[w]}, "
                               f"{hyp[w]['n_pairs']} pairs}}" for w in ws) + " \\\\",
             "".join(f"\\cmidrule({'lr' if i < len(ws) - 1 else 'l'}){{{2 + 2 * i}-{3 + 2 * i}}}"
                     for i in range(len(ws))),
             "Method & " + " & ".join(f"$k={SMALL_K}$ & $k={hyp[w]['kh']}$" for w in ws) + " \\\\", "\\midrule"]
    for row in rows:
        if row is None:
            lines.append("\\midrule")
            continue
        word, label = row
        lines.append(" & ".join([label] + [pr.fmt(errs[(w, k)][word]) for w in ws for k in (SMALL_K, hyp[w]["kh"])])
                     + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "table_ext.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--eval", required=True, type=Path, help="paper_eval's run of the second round")
    ap.add_argument("--nn", type=Path, default=None, help="paper_nn's run of the second round")
    ap.add_argument("--out", type=Path, default=None, help="default: the --eval directory")
    args = ap.parse_args()
    out = args.out or args.eval
    out.mkdir(parents=True, exist_ok=True)
    _, jobs, _ = pr.load(args.eval)
    nn_summary, nn_pairs = load_nn(args.nn)
    if args.nn:
        # H6's numerator comes from paper_nn's own recomputation of the course study's cells; it must
        # equal paper_eval's (README: paper_nn run with --reference, max_abs_log_diff 0).
        rc = nn_summary.get("reference_check")
        if rc is None:
            raise SystemExit(f"{args.nn} was run without --reference; rerun paper_nn.py with "
                             f"--reference {args.eval}/summary.json")
        if rc.get("missing") or rc.get("max_abs_log_diff") is None or rc["max_abs_log_diff"] > 1e-9:
            raise SystemExit(f"paper_nn's cells differ from paper_eval's: {rc.get('compared')} compared, "
                             f"{rc.get('missing')} missing, largest log difference {rc.get('max_abs_log_diff')}")
    hyp = {w: hypotheses(jobs, nn_pairs if args.nn else None, w) for w in EXPERIMENTS if pr.pairs_of(jobs, w)}
    for w, h in hyp.items():
        have = {r["pair"] for r in nn_pairs if r["workload"] == w}
        if args.nn and have != {r["pair"] for r in h["pairs"]}:
            print(f"warning: {w}: paper_nn has pairs {sorted(have)}, paper_eval {[r['pair'] for r in h['pairs']]}")
    checks = input_checks(hyp)
    for w, c in checks.items():
        print(f"{EXPERIMENTS[w]} ({w}): environments {', '.join(c['present'])}; split {c['split']['pool']} pool and "
              f"{c['split']['test']} test queries")
        if c["missing"]:
            print(f"  WARNING: registered environments without labels: {', '.join(c['missing'])}")
        for s in c["pairs_short"]:
            print(f"  WARNING: {s['pair']}: pool {s['pool']}, test {s['test']}, plan features differ in "
                  f"{s['features_differ']} queries")
    missing_exp = [w for w in EXPERIMENTS if w not in hyp]
    if missing_exp:
        print(f"WARNING: no pairs for {', '.join(missing_exp)}; H6 over all new pairs cannot hold")
    pooled = pooled_h6(hyp) if args.nn else {}
    doc = {"eval": ae.shown_path(args.eval), "nn": ae.shown_path(args.nn) if args.nn else None,
           "reference_check": nn_summary.get("reference_check") if nn_summary else None,
           "input_checks": checks, **hyp, "all": pooled}
    (out / "hypotheses_ext.json").write_text(json.dumps(doc, indent=1, default=float) + "\n", encoding="utf-8")
    write_macros(macros(jobs, hyp, nn_summary) | pooled_macros(pooled), out)
    table_hypotheses(hyp, out, pooled)
    table_errors(jobs, hyp, nn_summary, out)
    for w, h in hyp.items():
        print(f"{EXPERIMENTS[w]} ({w}): {h['n_pairs']} pairs, {h['processor_pairs']} with a processor change, kH = {h['kh']}")
        for test in TESTS:
            if test in h:
                verdict = ("holds" if h[test]["pass"] else "fails") if "pass" in h[test] else "descriptive"
                print(f"  {test}", verdict, {k: v for k, v in h[test].items() if k not in ("rule", "pass")})
    for test, p in pooled.items():
        print(f"all new pairs: {test}", "holds" if p["pass"] else "fails",
              {k: v for k, v in p.items() if k not in ("rule", "pass")})
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
