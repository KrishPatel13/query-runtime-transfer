GENERATED = "% Generated by src/paper_ext_report.py. Do not edit by hand."
EXPERIMENTS = {"tpch10": "E1", "job": "E2"}
WORKLOAD = {"tpch10": "TpchTen", "job": "Job"}          # as src/paper_nn_report.py spells them
DISPLAY = {"tpch10": "TPC-H SF10", "job": "JOB"}
SHORT = {"tpch10": "SF10", "job": "JOB"}               # table_ext, which must fit a column
PREFIX = "X"
TESTS = ["H1", "H2", "H3", "H4", "H5", "H6", "H6a", "H6b"]
SHARE_LEVEL, H4_LEVEL, H6B_LEVEL = 0.5, 1.15, 1.15
SMALL_K = 10
FT_MODES = ["full", "head"]          # H6 is about full fine-tuning; head-only is reported beside it

# Processor class of every environment: M1, M3 and M5 use all processors of their machine, M2 and M4
# one, M6 two.
PROCESSORS = {"M1": "all", "M2": "one", "M3": "all", "M4": "one", "M5": "all", "M6": "two"}

# Methods of the error macros and table_ext: (macro word, label, strategy, method), on the course
# study's source model from paper_eval, then the network fine-tuned on the same queries from paper_nn
# (round robin). The labels are short so that the table fits a column; the paper's caption gives the
# selection of each.
ERRORS = [("None", "No adaptation", "random", "none"), ("Speed", "Speed factor", "random", "speed"),
          ("AffinePar", "Affine+parallel", "random", "affine+parallel"),
          ("Ridge", "Ridge correction", "random", "ridge"),
          ("Primary", "Primary", *pr.PRIMARY), ("Knn", "1-NN", "k-center", "1-nn"),
          ("Oracle", "Oracle", "random", "oracle")]
NN_ERRORS = [("NnFull", "Network, fine-tuned", "nn:full-ft"),
             ("NnHead", "Network, head only", "nn:head-ft")]
HARD = [("None", "random|none"), ("Speed", "random|speed"), ("AffinePar", "random|affine+parallel"),
        ("Ridge", "random|ridge"), ("Oracle", "random|oracle")]


def processor_pair(pair: str) -> bool:
    """A pair of H3, "whose change includes the processor count": its two environments differ in
    processor class (PROCESSORS).

    On the first round's confirmatory machines, M1 to M4, this gives exactly that round's set: M1-M2,
    M3-M4, M1-M4 and M2-M3 in both directions, the pairs that paper_eval.CHANGE calls "processors" or
    "both" (tests/test_paper_ext.py checks it). In the second round every pair of E1 counts (M3, M4 and
    M6 are three classes), and every pair of E2 except M1-M3 and M2-M4.
    """
    a, b = pair.split("->")
    return PROCESSORS[a] != PROCESSORS[b]


# --------------------------------------------------------------- the rules

def every(ok: int, n: int) -> bool:
    return n > 0 and ok == n


def two_thirds(ok: int, n: int) -> bool:
    """At least two thirds, as paper_report's ok >= ceil(2 n / 3), in integers."""
    return n > 0 and 3 * ok >= 2 * n


def three_quarters(ok: int, n: int) -> bool:
    return n > 0 and 4 * ok >= 3 * n


def more_than_half(ok: int, n: int) -> bool:
    return n > 0 and 2 * ok > n


def gm_of(ratios: list[dict]) -> float | None:
    """Geometric mean over pairs of paired ratios' point estimates."""
    return float(np.exp(np.mean([np.log(r["gm"]) for r in ratios]))) if ratios else None


# ------------------------------------------------------------------ loading

def load_nn(run: Path | None) -> tuple[dict | None, list[dict]]:
    """paper_nn's summary and its pairs (each with its cells and H6 ratios); None and [] without a run."""
    if run is None:
        return None, []
    s = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    with gzip.open(run / "pairs.json.gz", "rt", encoding="utf-8") as f:
        return s, json.load(f)


# --------------------------------------------------------------- hypotheses

def pair_rows(jobs: dict, nn_pairs: list[dict], w: str) -> list[dict]:
    """Every moved pair of a workload with the statistics of H1 to H6b."""
    kh = pe.budget(w)
    nn_by = {r["pair"]: r for r in nn_pairs if r["workload"] == w}
    rows = []
    for pair in pr.pairs_of(jobs, w):
        j = jobs[(w, "hybrid", pair)]
        sh = j.get("shift", {})
        hard = j.get("hard", {})
        hs, ho = hard.get("random|speed", {}).get("q"), hard.get("random|oracle", {}).get("q")
        h6 = nn_by.get(pair, {}).get("h6", {})
        rows.append({
            "pair": pair, "change": j["change"], "processors": processor_pair(pair),
            "pool": j.get("pool"), "test": j.get("test"), "features_differ": j.get("features_differ"),
            "share": sh.get("template_share"), "share_noise": sh.get("share_noise"), "epsilon2": sh.get("epsilon2"),
            "h2_vs_speed": (pr.cell(j, *pr.PRIMARY, kh) or {}).get("vs_speed"),
            "h2_vs_ridge": (pr.cell(j, *pr.PRIMARY, kh) or {}).get("vs_ridge"),
            "h3": (pr.cell(j, "random", "affine+parallel", SMALL_K) or {}).get("vs_speed"),
            "h4_ratio": hs / ho if hs and ho else None,
            "h5": (pr.cell(j, "k-center", "1-nn", kh) or {}).get("vs_ridge"),
            "h6_kh": {m: h6.get(str(kh), {}).get(m) for m in FT_MODES},
            "h6_k10": {m: h6.get(str(SMALL_K), {}).get(m) for m in FT_MODES},
        })
    return rows


def hypotheses(jobs: dict, nn_pairs: list[dict] | None, w: str) -> dict:
    """H1 to H6b on the pairs of one workload. nn_pairs None: no neural run, no H6."""
    kh = pe.budget(w)
    rows = pair_rows(jobs, nn_pairs or [], w)
    proc = [r for r in rows if r["processors"]]
    out = {"experiment": EXPERIMENTS.get(w), "workload": w, "kh": kh, "n_pairs": len(rows),
           "processor_pairs": len(proc), "pairs": rows}
    if not rows:
        return out
    h1 = [r for r in rows if r["share"] is not None]
    noise = [r["share_noise"] for r in h1 if r["share_noise"] is not None]
    ok = sum(r["share"] > SHARE_LEVEL for r in h1)
    out["H1"] = {"rule": "template share > 0.5 in every pair", "ok": ok, "n": len(h1),
                 "min": min((r["share"] for r in h1), default=None),
                 "max": max((r["share"] for r in h1), default=None),
                 "noise_min": min(noise, default=None), "noise_max": max(noise, default=None),
                 "pass": every(ok, len(h1))}
    sp = [r["h2_vs_speed"] for r in rows if r["h2_vs_speed"]]
    rd = [r["h2_vs_ridge"] for r in rows if r["h2_vs_ridge"]]
    sp_ok, rd_ok = sum(c["gm_hi"] < 1 for c in sp), sum(c["gm_hi"] < 1 for c in rd)
    out["H2"] = {"rule": f"k={kh}: primary beats speed (CI < 1) in every pair and ridge (CI < 1) in >= 2/3",
                 "vs_speed_ok": sp_ok, "vs_ridge_ok": rd_ok, "n": len(sp), "n_ridge": len(rd),
                 "vs_speed_max_hi": max((c["gm_hi"] for c in sp), default=None),
                 "pass": every(sp_ok, len(sp)) and two_thirds(rd_ok, len(rd))}
    h3 = [r["h3"] for r in proc if r["h3"]]
    ok = sum(c["gm"] < 1 for c in h3)
    out["H3"] = {"rule": f"k={SMALL_K}: affine+parallel below speed in >= 3/4 of processor pairs", "ok": ok,
                 "ok_ci": sum(c["gm_hi"] < 1 for c in h3), "n": len(h3), "gm": gm_of(h3),
                 "pass": three_quarters(ok, len(h3))}
    h4 = [r["h4_ratio"] for r in rows if r["h4_ratio"] is not None]
    ok = sum(x <= H4_LEVEL for x in h4)
    out["H4"] = {"rule": "hard test: speed / oracle <= 1.15 in every pair", "ok": ok, "n": len(h4),
                 "max": max(h4, default=None), "pass": every(ok, len(h4))}
    h5 = [r["h5"] for r in rows if r["h5"]]
    ok = sum(c["gm"] < 1 for c in h5)
    out["H5"] = {"rule": f"k={kh}: k-center + 1-nn below random + ridge in >= 2/3", "ok": ok,
                 "ok_ci": sum(c["gm_hi"] < 1 for c in h5), "n": len(h5), "gm": gm_of(h5),
                 "pass": two_thirds(ok, len(h5))}
    if nn_pairs is None:
        return out
    for mode in FT_MODES:
        # The registered tests are on full fine-tuning; the same counts for head-only fine-tuning are
        # exploratory and carry its name.
        tag = "" if mode == "full" else "_head"
        big = [r["h6_kh"][mode] for r in rows if r["h6_kh"][mode]]
        small = [r["h6_k10"][mode] for r in rows if r["h6_k10"][mode]]
        ok = sum(c["gm_hi"] < 1 for c in big)
        # H6 is registered over all new pairs (pooled_h6); this experiment's count is descriptive and has
        # no "pass".
        out["H6" + tag] = {"rule": f"k={kh}: template correction below full fine-tuning (CI < 1), this "
                                   f"experiment's pairs (descriptive; H6 counts all new pairs)",
                           "ok": ok, "point": sum(c["gm"] < 1 for c in big), "n": len(big), "gm": gm_of(big)}
        point = sum(c["gm"] < 1 for c in small)
        gm = gm_of(small)
        out["H6a" + tag] = {"rule": f"k={SMALL_K}: ratio below 1 in more than half of the pairs, geometric mean < 1",
                            "point": point, "ok_ci": sum(c["gm_hi"] < 1 for c in small), "n": len(small), "gm": gm,
                            "pass": more_than_half(point, len(small)) and gm is not None and gm < 1}
        ok = sum(c["gm_hi"] < H6B_LEVEL for c in big)
        out["H6b" + tag] = {"rule": f"k={kh}: upper end of the ratio's interval < 1.15 in every pair", "ok": ok,
                            "n": len(big), "max_hi": max((c["gm_hi"] for c in big), default=None),
                            "pass": every(ok, len(big))}
    return out


def pooled_h6(hyp: dict) -> dict:
    """H6 as registered: "in at least two thirds of the new pairs", one count over the pairs of every
    experiment, each at its own kH. It holds only when every experiment of EXPERIMENTS was evaluated."""
    out = {}
    for mode in FT_MODES:
        tag = "" if mode == "full" else "_head"
        if not hyp or not all("H6" + tag in h for h in hyp.values()):
            continue
        big = [r["h6_kh"][mode] for h in hyp.values() for r in h["pairs"] if r["h6_kh"][mode]]
        ok = sum(c["gm_hi"] < 1 for c in big)
        out["H6" + tag] = {"rule": "kH: template correction below full fine-tuning (CI < 1) in >= 2/3 of all new pairs",
                           "ok": ok, "point": sum(c["gm"] < 1 for c in big), "n": len(big),
                           "n_pairs": sum(h["n_pairs"] for h in hyp.values()), "gm": gm_of(big),
                           "experiments": sorted(hyp),
                           "pass": set(hyp) == set(EXPERIMENTS) and two_thirds(ok, len(big))}
    return out


def input_checks(hyp: dict) -> dict:
    """What the run holds against what was registered: per experiment, the environments that entered
    and those of paper_eval.WORKLOADS without labels, and the pairs whose pool or test set is smaller
    than the split's or that left out queries with different plan features."""
    import pandas as pd

    out = {}
    for w, h in hyp.items():
        registered = sorted(pe.WORKLOADS[w]["runs"])
        present = sorted({m for r in h["pairs"] for m in r["pair"].split("->")})
        split = pd.read_csv(pe.HERE / pe.WORKLOADS[w]["split"])
        full = {s: int((split["set"] == s).sum()) for s in ("pool", "test")}
        short = [{"pair": r["pair"], "pool": r["pool"], "test": r["test"], "features_differ": r["features_differ"]}
                 for r in h["pairs"]
                 if (r["pool"] is not None and r["pool"] < full["pool"]) or (r["test"] is not None and r["test"] < full["test"])
                 or (r["features_differ"] or 0) > 0]
        out[w] = {"registered": registered, "present": present, "missing": sorted(set(registered) - set(present)),
                  "split": full, "pairs_short": short}
    return out


# ------------------------------------------------------------------ numbers

def fmt_level(x, level: float, d: int = 2) -> str:
    """fmt with up to four decimals when d would show x on or across the level it is compared with
    (1.1496 against 1.15 is 1.1496, not 1.15), so a shown value never contradicts its test."""
    if x is None or not np.isfinite(x):
        return "--"
    for dd in range(d, 5):
        r = round(float(x), dd)
        if r != level and (r < level) == (x < level):
            return f"{x:.{dd}f}"
    return f"{x:.4f}"


def errors(jobs: dict, nn_summary: dict | None, w: str, k: int) -> dict:
    """Geometric mean over the moved pairs of every method's error at k, and the no-move control."""
    js = [jobs[(w, "hybrid", p)] for p in pr.pairs_of(jobs, w)]
    out = {word: pr.geo([(pr.cell(j, s, m, k) or {}).get("q") for j in js]) for word, _, s, m in ERRORS}
    cs = [jobs[(w, "hybrid", p)] for p in pr.controls_of(jobs, w)]
    out["Control"] = pr.geo([(pr.cell(j, *pr.PRIMARY, k) or {}).get("q") for j in cs])
    if nn_summary is not None:
        gm = nn_summary["gm_over_pairs"].get(w, {}).get("round-robin", {})
        for word, _, m in NN_ERRORS:
            out[word] = gm.get(m, {}).get(str(k), float("nan"))
    return out


def hard_errors(jobs: dict, w: str) -> dict:
    js = [jobs[(w, "hybrid", p)] for p in pr.pairs_of(jobs, w)]
    return {word: pr.geo([j.get("hard", {}).get(key, {}).get("q") for j in js]) for word, key in HARD}


def macros(jobs: dict, hyp: dict, nn_summary: dict | None) -> dict:
    m = {}
    for w, h in hyp.items():
        W, kh = WORKLOAD[w], h["kh"]
        js = {p: jobs[(w, "hybrid", p)] for p in pr.pairs_of(jobs, w)}
        m[pr.tex_name(PREFIX, W, "pairs")] = str(h["n_pairs"])
        m[pr.tex_name(PREFIX, W, "proc pairs")] = str(h["processor_pairs"])
        m[pr.tex_name(PREFIX, W, "kH")] = str(kh)
        # The tests: every count, every level-compared number with enough decimals, and the result.
        level = {("H1", "min"): SHARE_LEVEL, ("H2", "vs_speed_max_hi"): 1.0, ("H3", "gm"): 1.0,
                 ("H4", "max"): H4_LEVEL, ("H5", "gm"): 1.0, ("H6", "gm"): 1.0, ("H6a", "gm"): 1.0,
                 ("H6b", "max_hi"): H6B_LEVEL}
        for test in [t for t in h if t.removesuffix("_head") in TESTS]:
            base = test.removesuffix("_head")
            for key, v in h[test].items():
                if key == "rule":
                    continue
                name = pr.tex_name(PREFIX, W, test.replace("_", " "), key)
                if isinstance(v, bool):
                    m[name] = "holds" if v else "fails"
                elif isinstance(v, (int, np.integer)):
                    m[name] = str(int(v))
                elif isinstance(v, float):
                    m[name] = fmt_level(v, level.get((base, key), np.inf), 3 if base.startswith("H6") else 2)
        # The shift: template share, its noise reference and epsilon squared over the pairs, and every
        # pair's median slowdown of all plans and of serial and parallel plans apart. A share is shown
        # with enough decimals that it never reads as being on the other side of H1's 0.5.
        for f in ("share", "share_noise", "epsilon2"):
            vals = [r[f] for r in h["pairs"] if r[f] is not None and np.isfinite(r[f])]
            if vals:
                show = (lambda x: fmt_level(x, SHARE_LEVEL)) if f == "share" else pr.fmt
                m[pr.tex_name(PREFIX, W, f, "min")] = show(min(vals))
                m[pr.tex_name(PREFIX, W, f, "max")] = show(max(vals))
        for p, j in js.items():
            sh = j.get("shift", {})
            if not sh:
                continue
            base = (PREFIX, W, p.replace("->", "to"))
            m[pr.tex_name(*base, "slowdown")] = pr.fmt(sh.get("median"))
            m[pr.tex_name(*base, "serial")] = pr.fmt(sh["by_plan"]["serial"]["median"])
            m[pr.tex_name(*base, "parallel")] = pr.fmt(sh["by_plan"]["parallel"]["median"])
            m[pr.tex_name(*base, "share")] = fmt_level(sh.get("template_share"), SHARE_LEVEL)
        # Errors at k = 10 and kH (geometric means over pairs), kH also under its own name, and the
        # hard test's.
        for k in (SMALL_K, kh):
            for word, v in errors(jobs, nn_summary, w, k).items():
                m[pr.tex_name(PREFIX, W, "k", k, word)] = pr.fmt(v)
                if k == kh:
                    m[pr.tex_name(PREFIX, W, "kH", word)] = pr.fmt(v)
        for word, v in hard_errors(jobs, w).items():
            m[pr.tex_name(PREFIX, W, "hard", word)] = pr.fmt(v)
        # What the first round's text quotes beside its tests (paper_report.extra_macros): the
        # affine+parallel line against the speed factor at k = 10 over all pairs, counted by interval,
        # the range of the primary method's error over the oracle's at kH, and the pairs where k-center
        # with 1-nn beats the primary method.
        a3 = [(pr.cell(j, "random", "affine+parallel", SMALL_K) or {}).get("vs_speed") or {} for j in js.values()]
        m[pr.tex_name(PREFIX, W, "aff below")] = str(sum(c.get("gm_hi", 9) < 1 for c in a3))
        m[pr.tex_name(PREFIX, W, "aff above")] = str(sum(c.get("gm_lo", 0) > 1 for c in a3))
        po = [(pr.cell(j, *pr.PRIMARY, kh) or {}).get("q") for j in js.values()]
        orc = [(pr.cell(j, "random", "oracle", kh) or {}).get("q") for j in js.values()]
        rat = [a / b for a, b in zip(po, orc) if a and b]
        if rat:
            m[pr.tex_name(PREFIX, W, "prim oracle min")] = pr.fmt(min(rat))
            m[pr.tex_name(PREFIX, W, "prim oracle max")] = pr.fmt(max(rat))
        nn1 = [(pr.cell(j, "k-center", "1-nn", kh) or {}).get("q") for j in js.values()]
        m[pr.tex_name(PREFIX, W, "nn below prim")] = str(sum(1 for a, b in zip(nn1, po) if a and b and a < b))
    return m


def pooled_macros(pooled: dict) -> dict:
    """XAllHSix<key> (and XAllHSixHead<key>): H6 over all new pairs."""
    m = {}
    for test, h in pooled.items():
        for key, v in h.items():
            if key in ("rule", "experiments"):
                continue
            name = pr.tex_name(PREFIX, "All", test.replace("_", " "), key)
            if isinstance(v, bool):
                m[name] = "holds" if v else "fails"
            elif isinstance(v, (int, np.integer)):
                m[name] = str(int(v))
            elif isinstance(v, float):
                m[name] = fmt_level(v, 1.0, 3)
    return m


def write_macros(m: dict, out: Path) -> None:
    lines = [GENERATED] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (out / "ext_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


