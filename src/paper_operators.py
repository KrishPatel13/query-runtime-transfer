"""Per-operator slowdowns for the paper, from the timing runs of scripts/node_timing.py.

For each pair of environments with timings on both sides, src/node_analysis
gives every operator type's median ratio of own time (target over source,
weighted by the source time), separately inside and outside the parallel
part of a plan. This script writes operators.csv with all of them and
operators.tex with the macros the paper quotes:

  OpProcParallel, OpProcSerial  processor change on the laptop (M1 to M2),
                                range over the main operator types inside
                                and outside the parallel part, both workloads
  OpMemIndex, OpMemSeq          buffer-pool change (M1 to M5): index scans
                                and sequential scans, range over workloads
                                and plan parts
  OpHwRange                     hardware change (M1 to M3), range over the
                                main operator types, when M3 was timed
A main operator type takes at least 3% of the source's time in that pair.

Usage: python src/paper_operators.py --runs results/runs --out results/paper/main
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

import node_analysis as na

GENERATED = "% Generated by src/paper_operators.py. Do not edit by hand."
PAIRS = [("tpch", "M1", "M2"), ("tpcds", "M1_tpcds", "M2_tpcds"),
         ("tpch", "M3", "M4"), ("tpcds", "M3_tpcds", "M4_tpcds"),
         ("tpch", "M1", "M5"), ("tpcds", "M1_tpcds", "M5_tpcds"),
         ("tpch", "M1", "M3"), ("tpcds", "M1_tpcds", "M3_tpcds")]
MIN_SHARE = 0.03


def find(runs: Path, machine: str) -> Path | None:
    for name in ("node_times.jsonl.gz", "node_times.jsonl"):
        p = runs / machine / name
        if p.exists():
            return p
    return None


def rng(values) -> str:
    v = sorted(values)
    if not v:
        return "--"
    return f"{v[0]:.1f}" if f"{v[0]:.1f}" == f"{v[-1]:.1f}" else f"{v[0]:.1f} to {v[-1]:.1f}"


COLUMNS = [("M1->M2", "Proc. (laptop)"), ("M3->M4", "Proc. (server)"), ("M1->M3", "Hardware"),
           ("M1->M5", "Buffer pool")]
ROWS = ["Seq Scan", "Index Scan", "Bitmap Heap Scan", "Hash Join", "Hash", "Nested Loop", "Sort",
        "Aggregate (Hashed)", "Aggregate (Sorted)"]


def table_operators(pooled: pd.DataFrame, out: Path) -> None:
    """Median own-time ratio per operator type, inside and outside the parallel part of plans,
    over the nodes of both workloads together, for each timed pair (pooled from summarize)."""
    cols = [(p, name) for p, name in COLUMNS if (pooled["pair"] == p).any()]
    lines = [GENERATED, "\\begin{tabular}{@{}l" + "rr" * len(cols) + "@{}}", "\\toprule",
             "& " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for _, name in cols) + " \\\\",
             "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(cols))),
             "Operator & " + " & ".join("par. & ser." for _ in cols) + " \\\\", "\\midrule"]
    for op in ROWS:
        cells = [op.replace("Aggregate (Hashed)", "Hash aggregate").replace("Aggregate (Sorted)", "Sorted aggregate")]
        any_value = False
        for p, _ in cols:
            for par in (True, False):
                g = pooled[(pooled["pair"] == p) & (pooled["type"] == op) & (pooled["parallel"] == par)]
                if len(g) and int(g["nodes"].iloc[0]) >= 20:
                    cells.append(f"{float(g['median_ratio'].iloc[0]):.2f}")
                    any_value = True
                else:
                    cells.append("--")
        if any_value:
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "table_operators.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", default="results/runs")
    ap.add_argument("--out", default="results/paper/main")
    args = ap.parse_args()
    runs, out = Path(args.runs), Path(args.out)
    frames, compared = [], {}
    for w, a, b in PAIRS:
        pa, pb = find(runs, a), find(runs, b)
        if pa is None or pb is None:
            continue
        A, B = na.load(pa), na.load(pb)
        if len(A) < 0.95 * len(set(A) | set(B)) or len(B) < 0.95 * len(set(A) | set(B)):
            print(f"skipping {a}->{b}: incomplete timings ({len(A)} and {len(B)} queries)")
            continue
        pair = f"{a.split('_')[0]}->{b.split('_')[0]}"
        c = na.compare(A, B)
        compared.setdefault(pair, []).append(c.assign(query_id=w + ":" + c["query_id"]))
        frames.append(na.summarize(c).assign(workload=w, pair=pair))
    if not frames:
        raise SystemExit("no pair with complete timings on both sides")
    d = pd.concat(frames, ignore_index=True)
    d.to_csv(out / "operators.csv", index=False)
    main_ops = d[(d["share_of_a_time"] >= MIN_SHARE) & ~d["type"].str.startswith("Gather")]
    m = {}
    proc = main_ops[main_ops["pair"] == "M1->M2"]
    m["OpProcParallel"] = rng(proc.loc[proc["parallel"], "median_ratio"])
    m["OpProcSerial"] = rng(proc.loc[~proc["parallel"], "median_ratio"])
    sproc = main_ops[main_ops["pair"] == "M3->M4"]
    if len(sproc):
        m["OpServerProcParallel"] = rng(sproc.loc[sproc["parallel"], "median_ratio"])
        m["OpServerProcSerial"] = rng(sproc.loc[~sproc["parallel"], "median_ratio"])
    mem = d[d["pair"] == "M1->M5"]
    m["OpMemIndex"] = rng(mem.loc[(mem["type"] == "Index Scan") & (mem["share_of_a_time"] >= 0.01), "median_ratio"])
    m["OpMemSeq"] = rng(mem.loc[(mem["type"] == "Seq Scan") & (mem["share_of_a_time"] >= 0.01), "median_ratio"])
    hw = main_ops[main_ops["pair"] == "M1->M3"]
    if len(hw):
        m["OpHwRange"] = rng(hw["median_ratio"])
    lines = [GENERATED] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (out / "operators.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    pooled = pd.concat([na.summarize(pd.concat(cs, ignore_index=True)).assign(pair=p)
                        for p, cs in compared.items()], ignore_index=True)
    pooled.to_csv(out / "operators_pooled.csv", index=False)
    table_operators(pooled, out)
    with pd.option_context("display.width", 200, "display.max_rows", 200):
        print(main_ops.round(3).to_string(index=False))
    print(m)


if __name__ == "__main__":
    main()
