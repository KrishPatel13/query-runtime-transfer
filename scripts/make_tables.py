"""Write the LaTeX results table and number macros used by the proposal and the pilot note.

Reads results/pilot/all22/summary.json and results/pilot/proposed5/summary.json
(written by src/train_eval.py) and the collection metadata, and writes
results/pilot/table_main.tex and results/pilot/numbers.tex, so that no result
in the documents is typed by hand.

Usage: python scripts/make_tables.py
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parents[1]
ALL = json.loads((HERE / "results/pilot/all22/summary.json").read_text(encoding="utf-8"))
FIVE = json.loads((HERE / "results/pilot/proposed5/summary.json").read_text(encoding="utf-8"))

ROWS = [("Cost-only", "Cost-only (baseline)"), ("Ridge", "Ridge"), ("Random Forest", "Random forest"),
        ("Cost + RF residual", "Cost + RF residual$^{\\ast}$"), ("Template mean", "Template mean$^{\\dagger}$"),
        ("Global mean", "Global mean$^{\\ddagger}$")]
REFERENCES = ("Template mean", "Global mean")


def e2_cell(summary: dict, model: str) -> str:
    r = summary["e2_pooled"].get(model)
    if r is None:
        return "--"
    return f"{r['median_q']:.2f} [{r['ci_lo']:.2f}, {r['ci_hi']:.2f}]"


def five_cell(model: str) -> str:
    """E2 with only five templates: the pooled median and the range of the
    five per-template medians. Five templates allow only 126 distinct
    bootstrap resamples, too few for a 95% interval."""
    r = FIVE["e2_pooled"].get(model)
    if r is None:
        return "--"
    per_t = [v[model] for v in FIVE["e2_per_template"].values()]
    return f"{r['median_q']:.2f} [{min(per_t):.2f}, {max(per_t):.2f}]"


def ratio_cell(model: str) -> str:
    """Primary paired statistic: geometric mean over held-out templates of the
    model's per-template median Q-error divided by the cost line's."""
    p = ALL["e2_paired_vs_cost"].get(model)
    if p is None:
        return "--"
    return f"{p['gm']:.2f} [{p['gm_lo']:.2f}, {p['gm_hi']:.2f}]"


def main() -> None:
    n_t = len(ALL["e2_per_template"])
    lines = [
        "% Generated by scripts/make_tables.py from results/pilot/*/summary.json. Do not edit by hand.",
        "\\begin{tabular}{@{}lccccccc@{}}",
        "\\toprule",
        " & \\multicolumn{2}{c}{Seen templates (E1)} & \\multicolumn{4}{c}{Unseen template (E2), 22 templates}"
        " & E2, only 5 templates \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}\\cmidrule(l){8-8}",
        "Model & median $Q$ & P90 $Q$ & median $Q$ [95\\% CI] & P90 $Q$ & ratio to cost [95\\% CI] & beats cost"
        " & median $Q$ [range] \\\\",
        "\\midrule",
    ]
    for key, label in ROWS:
        e1 = ALL["e1"].get(key)
        e1_cells = f"{e1['median_q']:.2f} $\\pm$ {e1['median_q_std']:.2f} & {e1['p90_q']:.2f}" if e1 else "-- & --"
        if key in ALL["e2_pooled"]:
            r = ALL["e2_pooled"][key]
            wins = "--" if key == "Cost-only" else f"{ALL['e2_wins_vs_cost'][key]}/{n_t}"
            e2_cells = f"{e2_cell(ALL, key)} & {r['p90_q']:.2f} & {ratio_cell(key)} & {wins}"
        else:
            e2_cells = "-- & -- & -- & --"
        if key == REFERENCES[0]:
            lines.append("\\midrule")
        lines.append(f"{label} & {e1_cells} & {e2_cells} & {five_cell(key)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out = HERE / "results/pilot/table_main.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    write_macros()
    print(out.read_text(encoding="utf-8"))


CODE = {"Cost-only": "Cost", "Ridge": "Ridge", "Random Forest": "RF", "Cost + RF residual": "Hyb",
        "Template mean": "TM", "Global mean": "GM"}


def minutes(meta_path: Path) -> float:
    run = json.loads(meta_path.read_text(encoding="utf-8"))[-1]
    start, end = (dt.datetime.fromisoformat(run[k]) for k in ("started_at", "finished_at"))
    return (end - start).total_seconds() / 60


def write_macros() -> None:
    """Every number quoted in the running text of the documents, as LaTeX macros
    (TeX names allow letters only, so E1 is Eone, P90 is Pninety, and so on)."""
    d = ALL["data"]
    m = {
        "NQueries": d["n_ok"], "NTemplates": d["n_templates"],
        "RuntimeMin": f"{d['runtime_ms']['min']:.0f}", "RuntimeMax": f"{d['runtime_ms']['max']:.0f}",
        "WithinMax": f"{d['within_template_max_over_min']['max']:.2f}",
        "WithinMedian": f"{d['within_template_max_over_min']['median']:.2f}",
        "RepeatMedian": f"{d['repeat_qerror_vs_median']['median']:.2f}",
        "RepeatPninety": f"{d['repeat_qerror_vs_median']['p90']:.2f}",
        "CollectMinutes": f"{minutes(HERE / 'results/pilot/runtime_dataset.meta.json'):.0f}",
        "CollectMinutesPassTwo": f"{minutes(HERE / 'results/pilot/pass2/runtime_dataset.meta.json'):.0f}",
    }
    for model, c in CODE.items():
        e1 = ALL["e1"].get(model)
        if e1:
            m[f"Eone{c}Med"], m[f"Eone{c}Pninety"] = f"{e1['median_q']:.2f}", f"{e1['p90_q']:.2f}"
        for frac, word in (("0.1", "Ten"), ("0.25", "Quarter")):
            if model in ALL["e3"][frac]:
                m[f"Ethree{c}{word}"] = f"{ALL['e3'][frac][model]:.2f}"
        for tag, s in (("Etwo", ALL), ("Five", FIVE)):
            r = s["e2_pooled"].get(model)
            if r is None:
                continue
            m[f"{tag}{c}Med"], m[f"{tag}{c}Pninety"] = f"{r['median_q']:.2f}", f"{r['p90_q']:.2f}"
            m[f"{tag}{c}Lo"], m[f"{tag}{c}Hi"] = f"{r['ci_lo']:.2f}", f"{r['ci_hi']:.2f}"
            per_t = {int(t): v[model] for t, v in s["e2_per_template"].items()}
            worst = max(per_t, key=per_t.get)
            m[f"{tag}{c}Worst"], m[f"{tag}{c}WorstT"] = f"{per_t[worst]:.2f}", f"Q{worst}"
            # The cost line's median Q-error on this model's worst template.
            m[f"{tag}{c}WorstCost"] = f"{s['e2_per_template'][str(worst)]['Cost-only']:.2f}"
            m[f"{tag}{c}Best"] = f"{min(per_t.values()):.2f}"
            # Median over held-out templates of each template's median Q-error:
            # the per-template summary that the sign test and E4 use.
            m[f"{tag}{c}PerT"] = f"{float(np.median(list(per_t.values()))):.2f}"
            if model != "Cost-only":
                m[f"{tag}{c}Wins"] = s["e2_wins_vs_cost"][model]
                p = s["e2_paired_vs_cost"][model]
                m[f"{tag}{c}Ratio"], m[f"{tag}{c}RatioLo"] = f"{p['ratio']:.2f}", f"{p['ratio_lo']:.2f}"
                m[f"{tag}{c}RatioHi"], m[f"{tag}{c}SignP"] = f"{p['ratio_hi']:.2f}", f"{p['sign_p']:.3f}"
                m[f"{tag}{c}WilcoxP"] = f"{p['wilcoxon_p']:.3f}"
                m[f"{tag}{c}Geo"], m[f"{tag}{c}GeoLo"] = f"{p['gm']:.2f}", f"{p['gm_lo']:.2f}"
                m[f"{tag}{c}GeoHi"] = f"{p['gm_hi']:.2f}"
    m["PowerTemplates"] = templates_for_power()
    for k, row in ALL["e4"].items():
        word = NUMBER_WORDS[int(k)]
        for model, c in CODE.items():
            if model in row:
                m[f"Efour{c}K{word}"] = f"{row[model]['median']:.2f}"
    lines = ["% Generated by scripts/make_tables.py from results/pilot/*/summary.json and the collection",
             "% metadata. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (HERE / "results/pilot/numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def templates_for_power(model: str = "Cost + RF residual", power: float = 0.8) -> int:
    """Held-out templates needed for a two-sided one-sample t-test on the
    per-template log ratios (model / cost line) to reach the given power at
    alpha = 0.05, if the pilot's mean and spread of those ratios hold."""
    from scipy.stats import nct, t as tdist
    lr = np.array([np.log(v[model] / v["Cost-only"]) for v in ALL["e2_per_template"].values()])
    d = abs(lr.mean()) / lr.std(ddof=1)
    for n in range(3, 10000):
        crit = tdist.ppf(0.975, n - 1)
        achieved = 1 - nct.cdf(crit, n - 1, d * np.sqrt(n)) + nct.cdf(-crit, n - 1, d * np.sqrt(n))
        if achieved >= power:
            return n
    raise ValueError("effect too small")


NUMBER_WORDS = {1: "One", 2: "Two", 3: "Three", 4: "Four", 6: "Six", 8: "Eight", 12: "Twelve",
                16: "Sixteen", 21: "TwentyOne"}


if __name__ == "__main__":
    main()
