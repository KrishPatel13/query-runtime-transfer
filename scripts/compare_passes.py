"""Compare two independent collection passes over the same queries.

Reports how closely the runtime labels agree (as a Q-error between the two
passes' median labels) and whether PostgreSQL chose the same plan both times
(same node tree and same estimated costs).

A pass can also shift level partway through, for example when the laptop
sleeps or Windows switches on its energy saver. The script therefore looks for
the single point in pass 2's execution order where the pass 2 / pass 1 ratio
changes most, and reports the agreement before and after it when the shift is
larger than 10%. It also reports the longest gap between two consecutive
queries.

The plan comparison, the level-shift test and the agreement statistics are in
src/passcheck.py, which src/run_passes.py and src/make_labels.py use too.

Writes results/pilot/pass2/reproducibility.json and results/pilot/pass2_numbers.tex
(LaTeX macros, so the documents never quote these numbers by hand).

Usage: python scripts/compare_passes.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / "src"))

# change_point, shape and agreement used to be defined here, and
# scripts/pilot_adaptation.py still imports change_point from this module.
from passcheck import MIN_SEGMENT, MIN_SHIFT, agreement, change_point, compare, shape  # noqa: E402,F401

P1 = HERE / "results/pilot"
P2 = HERE / "results/pilot/pass2"


def main() -> None:
    a = pd.read_csv(P1 / "runtime_dataset.csv")
    b = pd.read_csv(P2 / "runtime_dataset.csv")
    out = compare(a, b, P1 / "plans", P2 / "plans")
    shift = out["shift"]
    (P2 / "reproducibility.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")

    macros = {"PassTwoN": out["n_compared"], "PassTwoSamePlan": out["same_plan"],
              "PassTwoMedQ": f"{out['all']['median_q']:.2f}", "PassTwoPninetyQ": f"{out['all']['p90_q']:.2f}",
              "PassTwoCorr": f"{out['all']['log_corr']:.3f}"}
    if shift:
        macros |= {
            "PassTwoShiftAfter": shift["after_query_number"],
            "PassTwoShiftAt": shift["at"][11:16],
            "PassTwoBeforeMedQ": f"{shift['before']['median_q']:.2f}",
            "PassTwoBeforePninetyQ": f"{shift['before']['p90_q']:.2f}",
            "PassTwoBeforeMaxQ": f"{shift['before']['max_q']:.2f}",
            "PassTwoBeforeCorr": f"{shift['before']['log_corr']:.3f}",
            "PassTwoBeforeWithin": f"{shift['before']['within_template_corr']:.2f}",
            "PassTwoAfterRatio": f"{shift['after']['median_ratio']:.2f}",
            "PassTwoAfterRatioPten": f"{shift['after']['ratio_p10']:.2f}",
            "PassTwoAfterRatioPninety": f"{shift['after']['ratio_p90']:.2f}",
            "PassTwoAfterCorr": f"{shift['after']['log_corr']:.3f}",
            "PassTwoAfterSpearman": f"{shift['after']['spearman']:.3f}",
            "PassTwoAfterWithin": f"{shift['after']['within_template_corr']:.2f}",
            "PassTwoAfterSlowerPct": f"{100 * shift['share_slower_after']:.0f}",
        }
    (HERE / "results/pilot/pass2_numbers.tex").write_text(
        "% Generated by scripts/compare_passes.py. Do not edit by hand.\n" +
        "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()), encoding="utf-8", newline="\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
